// Builds dist/tokens.css (light + dark + reduced motion) and dist/index.{js,d.ts}.
import StyleDictionary from 'style-dictionary';
import { mkdir, writeFile } from 'node:fs/promises';

const PREFIX = 'cr';
// :where() keeps both dark selectors as specific as a plain :root, so an app's own :root rule,
// loaded after this file, overrides a token in both themes.
const DARK = ':root:where([data-theme="dark"])';
// Doubled so an app's :root rule cannot undo what a person asked their system for.
const FIRM = ':root:root';

function dictionary(theme) {
  return new StyleDictionary({
    source: ['src/primitive/*.json', `src/semantic/${theme}.json`],
    usesDtcg: true,
    log: { verbosity: 'silent' },
    platforms: {
      css: {
        // Values pass through as authored; only names are transformed.
        transforms: ['name/kebab'],
        prefix: PREFIX,
        files: [
          {
            destination: 'tokens.css',
            format: 'css/variables',
            filter: theme === 'dark' ? (t) => t.filePath.includes('semantic/dark') : undefined,
            options: {
              selector: theme === 'dark' ? DARK : ':root',
              outputReferences: true,
              showFileHeader: false,
            },
          },
        ],
      },
    },
  });
}

const light = dictionary('light');
const dark = dictionary('dark');
const [[lightCss], [darkCss]] = await Promise.all([
  light.formatPlatform('css').then((o) => o.map((f) => f.output)),
  dark.formatPlatform('css').then((o) => o.map((f) => f.output)),
]);

// color-scheme makes native controls (scrollbars, <progress>, form fields) follow the theme.
const withScheme = (block, scheme) => block.replace('{', `{\n  color-scheme: ${scheme};`);
// Solid mode: every glass layer opaque, no blur.
const SOLID = ['window', 'tile', 'sheet', 'popover', 'control']
  .map((layer) => `\n  --${PREFIX}-glass-opacity-${layer}: 100%;`)
  .concat(['window', 'sheet'].map((layer) => `\n  --${PREFIX}-glass-filter-${layer}: none;`))
  .join('') + '\n';
const darkBody = withScheme(darkCss, 'dark').slice(darkCss.indexOf('{') + 1, -2);
const css = `/* Generated by creance-tokens. Do not edit. */
${withScheme(lightCss, 'light')}
@media (prefers-color-scheme: dark) {
  :root:where(:not([data-theme="light"])) {${darkBody}}
}

${withScheme(darkCss, 'dark')}
/* Solid surfaces and no blur when the person asks for less transparency or more contrast. */
@media (prefers-reduced-transparency: reduce), (prefers-contrast: more) {
  ${FIRM} {${SOLID}  }
}
:root[data-transparency="reduce"] {${SOLID}}

@media (prefers-reduced-motion: reduce) {
  ${FIRM} {
    --${PREFIX}-motion-duration-fast: 0ms;
    --${PREFIX}-motion-duration-base: 0ms;
    --${PREFIX}-motion-duration-slow: 0ms;
  }
}
`;

// JS export: `tokens` holds var() references (theme-aware), `values` holds resolved light values.
const { allTokens } = await light.getPlatformTokens('css');
const tokens = {};
const values = {};
for (const t of allTokens) {
  set(tokens, t.path, `var(--${t.name})`);
  set(values, t.path, t.$value);
}
function set(obj, path, value) {
  const last = path.length - 1;
  path.slice(0, last).reduce((o, k) => (o[k] ??= {}), obj)[path[last]] = value;
}

const json = (o) => JSON.stringify(o, null, 2);
await mkdir('dist', { recursive: true });
await Promise.all([
  writeFile('dist/tokens.css', css),
  writeFile('dist/index.js', `export const tokens = ${json(tokens)};\n\nexport const values = ${json(values)};\n`),
  // A JSON object literal is also a valid TS type literal, which gives exact key and value types.
  writeFile(
    'dist/index.d.ts',
    `export declare const tokens: ${json(tokens)};\n\nexport declare const values: ${json(values)};\n`,
  ),
]);
console.log(`creance-tokens: ${allTokens.length} tokens built`);
